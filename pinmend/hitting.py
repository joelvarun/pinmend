"""Exact minimum hitting set by branch and bound.

The repair loop calls this once per iteration on the cores collected so far.
Instances are tiny (a handful of cores over a dozen requirement lines), so an
exact method costs nothing and is what makes the final answer provably minimal
instead of merely small.
"""

from __future__ import annotations

def prune_dominated(cores: list[frozenset[int]]) -> list[frozenset[int]]:
    """Drop any core that strictly contains another: only minimal ones bind."""
    unique = sorted(set(cores), key=lambda c: (len(c), sorted(c)))
    kept: list[frozenset[int]] = []
    for core in unique:
        if not any(other <= core for other in kept):
            kept.append(core)
    return kept


def greedy_hitting_set(cores: list[frozenset[int]]) -> frozenset[int]:
    remaining = list(cores)
    chosen: set[int] = set()
    while remaining:
        freq: dict[int, int] = {}
        for core in remaining:
            for element in core:
                freq[element] = freq.get(element, 0) + 1
        pick = max(sorted(freq), key=lambda e: freq[e])
        chosen.add(pick)
        remaining = [c for c in remaining if pick not in c]
    return frozenset(chosen)


def _disjoint_lower_bound(cores: list[frozenset[int]]) -> int:
    """Any hitting set needs one element per pairwise-disjoint core."""
    used: set[int] = set()
    count = 0
    for core in sorted(cores, key=len):
        if not (core & used):
            count += 1
            used |= core
    return count


def min_hitting_set(cores: list[frozenset[int]]) -> frozenset[int]:
    cores = prune_dominated([c for c in cores if c])
    if not cores:
        return frozenset()
    best = greedy_hitting_set(cores)
    best_size = len(best)
    result = {"set": best}

    def recurse(unhit: list[frozenset[int]], chosen: frozenset[int]) -> None:
        nonlocal best_size
        if not unhit:
            if len(chosen) < best_size:
                best_size = len(chosen)
                result["set"] = chosen
            return
        if len(chosen) + _disjoint_lower_bound(unhit) >= best_size:
            return
        pivot = min(unhit, key=lambda c: (len(c), sorted(c)))
        for element in sorted(pivot):
            recurse([c for c in unhit if element not in c], chosen | {element})

    recurse(cores, frozenset())
    return result["set"]


def minimal_hitting_sets(cores: list[frozenset[int]], max_size: int) -> list[frozenset[int]]:
    """Every minimal hitting set of the cores up to a size bound.

    Branches on one unhit core at a time, so the work scales with the product
    of the core sizes rather than with the number of subsets of the file. The
    repair loop needs this at exactly the minimum cardinality, where a hitting
    set of that size cannot contain a smaller one and is therefore minimal:
    the enumeration is complete there.
    """
    cores = prune_dominated([c for c in cores if c])
    if not cores:
        return [frozenset()]
    found: set[frozenset[int]] = set()

    def recurse(unhit: list[frozenset[int]], chosen: frozenset[int]) -> None:
        if len(chosen) > max_size:
            return
        if not unhit:
            found.add(chosen)
            return
        pivot = min(unhit, key=lambda c: (len(c), sorted(c)))
        for element in sorted(pivot):
            recurse([c for c in unhit if element not in c], chosen | {element})

    recurse(cores, frozenset())
    kept: list[frozenset[int]] = []
    for candidate in sorted(found, key=lambda h: (len(h), sorted(h))):
        if not any(other < candidate for other in kept):
            kept.append(candidate)
    return kept


def pad_to_size(cores, universe: list[int], size: int, cap: int = 20_000):
    """Every hitting set of exactly `size`, minimal or not, up to a cap.

    A repair may deliberately unpin a line it does not strictly need, because
    the extra freedom can land the rest of the plan closer to the pinned
    versions. Those sets are supersets of minimal hitting sets, so they are
    generated by padding. Returns (candidates, exhaustive).
    """
    from itertools import combinations

    base = [h for h in minimal_hitting_sets(cores, size) if len(h) <= size]
    out: set[frozenset[int]] = {h for h in base if len(h) == size}
    for seed in base:
        shortfall = size - len(seed)
        if shortfall <= 0:
            continue
        spare = [e for e in universe if e not in seed]
        for combo in combinations(spare, shortfall):
            out.add(seed | frozenset(combo))
            if len(out) > cap:
                return sorted(out, key=lambda h: sorted(h)), False
    return sorted(out, key=lambda h: sorted(h)), True
